import SwiftUI

struct HistoryView: View {
    @EnvironmentObject private var store: POStore
    @EnvironmentObject private var authStore: AuthStore
    @State private var searchText = ""
    @State private var sort: HistorySort = .dateNewest

    /// History filtered by the search term (customer name or job number) and sorted.
    private var displayedHistory: [PurchaseOrder] {
        let query = searchText.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        let filtered = query.isEmpty ? store.history : store.history.filter {
            $0.customerName.lowercased().contains(query)
                || $0.jobNumber.lowercased().contains(query)
        }
        return sort.sorted(filtered)
    }

    var body: some View {
        NavigationStack {
            Group {
                if store.history.isEmpty && !store.isLoadingHistory {
                    emptyState
                } else if displayedHistory.isEmpty {
                    noMatchesState
                } else {
                    List(displayedHistory) { po in
                        NavigationLink(value: po) {
                            VStack(alignment: .leading, spacing: 4) {
                                HStack {
                                    Text(po.poNumber)
                                        .font(.system(.body, design: .monospaced))
                                        .bold()
                                        .foregroundColor(Theme.accent)
                                    Spacer()
                                    statusMenu(for: po)
                                }
                                Text("\(po.customerName) · Job \(po.jobNumber)")
                                    .font(.subheadline)
                                    .foregroundColor(.secondary)
                                Text("By \(po.createdByName) · \(po.createdAt.formatted(date: .abbreviated, time: .shortened))")
                                    .font(.caption)
                                    .foregroundColor(.secondary)
                            }
                            .padding(.vertical, 2)
                        }
                        .listRowBackground(Theme.panel)
                    }
                    .scrollContentBackground(.hidden)
                    .background(Theme.background)
                    .navigationDestination(for: PurchaseOrder.self) { po in
                        PODetailView(po: po)
                    }
                    .refreshable {
                        await store.loadHistory()
                    }
                }
            }
            .navigationTitle("HISTORY")
            .searchable(text: $searchText, prompt: "Customer or job number")
            .toolbar {
                ToolbarItem(placement: .topBarTrailing) {
                    sortMenu
                }
            }
            .task {
                await store.loadHistory()
            }
        }
    }

    private var emptyState: some View {
        VStack(spacing: 12) {
            Image(systemName: "shippingbox")
                .font(.system(size: 40))
                .foregroundColor(Theme.steel)
            Text("No POs Yet")
                .font(.headline)
            Text("Purchase orders generated by you or your team will show up here.")
                .font(.subheadline)
                .foregroundColor(.secondary)
                .multilineTextAlignment(.center)
                .padding(.horizontal, 32)
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .background(Theme.background)
    }

    private var noMatchesState: some View {
        VStack(spacing: 12) {
            Image(systemName: "magnifyingglass")
                .font(.system(size: 40))
                .foregroundColor(Theme.steel)
            Text("No Matches")
                .font(.headline)
            Text("No purchase orders match \"\(searchText)\".")
                .font(.subheadline)
                .foregroundColor(.secondary)
                .multilineTextAlignment(.center)
                .padding(.horizontal, 32)
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .background(Theme.background)
    }

    private var sortMenu: some View {
        Menu {
            Picker("Sort", selection: $sort) {
                ForEach(HistorySort.allCases) { option in
                    Label(option.label, systemImage: option.systemImage).tag(option)
                }
            }
        } label: {
            Label("Sort", systemImage: "arrow.up.arrow.down")
        }
    }

    private func statusMenu(for po: PurchaseOrder) -> some View {
        Menu {
            ForEach(POStatus.allCases) { status in
                Button {
                    store.setStatus(status, for: po, by: authStore.currentUser)
                } label: {
                    Label(status.label, systemImage: status.systemImage)
                }
            }
        } label: {
            Label(po.status.label, systemImage: po.status.systemImage)
                .font(.caption2)
                .lineLimit(1)
                .minimumScaleFactor(0.8)
                .foregroundColor(po.status.color)
                // Constant footprint so the row is the same size for every status.
                .frame(width: 108, alignment: .trailing)
        }
        .menuStyle(.borderlessButton)
    }
}

#Preview {
